/// Translate a canonical bus path to the legacy name the HMI expects.
/// Falls through unchanged when there is no alias.
pub fn to_hmi(canonical: VssPath) -> VssPath {
    HMI_ALIASES
        .iter()
        .find(|(c, _)| *c == canonical)
        .map(|(_, legacy)| *legacy)
        .unwrap_or(canonical)
}

/// Translate a legacy HMI path to its canonical bus equivalent.
/// Falls through unchanged when there is no alias (the caller then
/// matches against the canonical signal lists and rejects unknowns).
pub fn from_hmi(legacy: &str) -> &str {
    HMI_ALIASES
        .iter()
        .find(|(_, l)| *l == legacy)
        .map(|(canon, _)| *canon)
        .unwrap_or(legacy)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips_every_alias() {
        for (canon, legacy) in HMI_ALIASES {
            assert_eq!(to_hmi(canon), *legacy, "to_hmi({canon})");
            assert_eq!(from_hmi(legacy), *canon, "from_hmi({legacy})");
        }
    }

    #[test]
    fn unknown_paths_pass_through() {
        assert_eq!(
            to_hmi("Vehicle.Nonexistent.Path"),
            "Vehicle.Nonexistent.Path"
        );
        assert_eq!(from_hmi("Body.Nonexistent.Path"), "Body.Nonexistent.Path");
    }

    #[test]
    fn aliases_are_unique_both_directions() {
        use std::collections::HashSet;
        let canon: HashSet<_> = HMI_ALIASES.iter().map(|(c, _)| *c).collect();
        let legacy: HashSet<_> = HMI_ALIASES.iter().map(|(_, l)| *l).collect();
        assert_eq!(canon.len(), HMI_ALIASES.len(), "duplicate canonical key");
        assert_eq!(legacy.len(), HMI_ALIASES.len(), "duplicate legacy key");
    }
}
