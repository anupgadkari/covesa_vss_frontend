//! HMI path-vocabulary translation shim.
//!
//! The web HMI speaks the project's legacy signal vocabulary
//! (`Body.*` / `Cabin.*` / `Chassis.*`), while the bus is now on the
//! canonical / project namespaces decided in the VSS v6.0 refresh
//! (`Vehicle.*` / `Vehicle.Controller.*` / `Vehicle.Simulation.*`).
//!
//! Rather than rename the HMI's compositional path construction
//! (prefix props, template literals, string concat — ~270 references
//! that a literal rename can't safely reach), we translate at the
//! WebSocket boundary in `ws_bridge`:
//!
//!   - **outbound** (bus → HMI): canonical key → legacy key via
//!     [`to_hmi`], so the HMI's `s["Body.Hood.IsOpen"]` lookups resolve.
//!   - **inbound** (HMI → bus): legacy `path` → canonical via
//!     [`from_hmi`], so it matches the canonical `INPUT_SIGNALS` list.
//!
//! Paths with no alias (already-canonical signals, or HMI-only display
//! paths that never cross the bus) pass through unchanged.
//!
//! This table is generated from `docs/vss-v6.0-path-mapping.csv` with
//! the KeyFob/BlePhone/NfcCard simplification folded in.  When the HMI
//! is itself canonicalised (a future, Playwright-verified sub-PR) this
//! whole module is deleted.

